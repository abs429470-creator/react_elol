// ============================================================
// TaskList.jsx - קומפוננטה שמציגה את רשימת המשימות (קומפוננטת ילד)
// ============================================================
// הקומפוננטה הזו מקבלת מהאב מערך של משימות (props בשם tasks)
// ומציירת כל אחת מהן על המסך. היא לא יודעת מאיפה הנתונים באו -
// וזה בדיוק היתרון: קומפוננטה עצמאית, ממוקדת, וקלה לשימוש חוזר.
// ============================================================

// כאן אנחנו מקבלים רק את השדה tasks מתוך ה-props.
// (האב יכול להעביר עוד שדות - אנחנו מתעלמים מהם, וזה בסדר גמור.)
function TaskList({ tasks }) {
  return (
    <section className="task-list">
      <h2>רשימת המשימות</h2>

      {/* <ul> = Unordered List (רשימה ללא מספור), <li> = List Item (פריט ברשימה) */}
      <ul>
        {/*
          כאן קורה הקסם המרכזי של React: בתוך JSX אפשר לכתוב ביטוי
          JavaScript בתוך { }. במקרה הזה אנחנו קוראים למתודה map
          על המערך tasks.

          map = מתודה של מערך שמקבלת פונקציה, מפעילה אותה פעם אחת
          על כל איבר, ואוספת את התוצאות למערך חדש. כלומר:
          "תרגם כל אובייקט-משימה למה שיוצג על המסך".

          בשביל ש-React תדע לזהות כל פריט, חובה לתת לכל פריט תג
          key ייחודי ויציב. כאן משתמשים ב-task.id (ולא במספר הרץ של
          המעבר) - כך React תדע לזהות את הפריט הנכון גם אם הסדר ישתנה
          בעתיד. key לא מוצג למשתמש; הוא רק "תעודת זהות" פנימית.
        */}
        {tasks.map((task) => (
          <li key={task.id}>
            {/* task.name ו-task.status מגיעים מהאב */}
            <span className="task-name">{task.name}</span>
            <span className="task-status">{task.status}</span>
          </li>
        ))}
      </ul>
    </section>
  )
}

export default TaskList
