// ============================================================
// Summary.jsx - קומפוננטה שמציגה סיכום מספרי (קומפוננטת ילד)
// ============================================================

// כבר אין צורך בקבוע DONE_STATUS='הושלמה', כי המצב כעת הוא
// שדה בוליאני completed (true/false) ולא מחרוזת. פשוט וקריא יותר.

// מקבלים שני שדות מתוך ה-props: את כל המשימות ואת שם המשתמש.
function Summary({ tasks, userName }) {
  // ---------- חישובים ----------

  // tasks.length = כמה איברים יש במערך, כלומר "כמה משימות יש סה"כ".
  const totalCount = tasks.length

  // filter = מתודה של מערך שמחזירה מערך חדש עם רק האיברים
  // שהפונקציה החזירה לגביהם true. כאן: רק המשימות שהושלמו
  // (completed === true, אפשר לקצר ל-task.completed בלבד).
  const doneTasks = tasks.filter((task) => task.completed)

  // וכמה הן? גם כאן - שוב length, רק על המערך המסונן.
  const doneCount = doneTasks.length

  // ---------- תצוגה ----------
  return (
    <section className="summary">
      <h2>סיכום</h2>

      {/*
        בתוך JSX אפשר לכתוב כל ביטוי JavaScript בתוך { }.
        התבנית `${...}` שבתוך המחרוזת נקראת template literal -
        היא מאפשרת לשלב ערכים בתוך מחרוזת בלי "להדביק" בחיבור (+) ידני.

        שימו לב: userName מגיע מהאב, אך החישוב עצמו נעשה בתוך
        הקומפוננטה הזו - לפי הנתונים בלבד. זו נקודה חשובה:
        קומפוננטה טובה גוזרת את מה שהיא מציגה מהנתונים שקיבלה.
      */}
      <p>
        שלום {userName}, יש לך {totalCount} משימות, מתוכן {doneCount} הושלמו.
      </p>
    </section>
  )
}

export default Summary
