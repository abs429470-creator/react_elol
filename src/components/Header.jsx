// ============================================================
// Header.jsx - קומפוננטת כותרת (קומפוננטת ילד)
// ============================================================
// קומפוננטה = פונקציה שמחזירה JSX (תיאור של מה שיוצג על המסך).
// הפונקציה מקבלת פרמטר אחד - props - שהוא אובייקט עם כל הנתונים
// שהקומפוננטה-האב העבירה לה.
// ============================================================

// הסוגריים המסולסלים סביב { user } ו-{ siteName } הם "destructuring":
// במקום לכתוב props.user ו-props.siteName, אנחנו "שולפים" החוצה
// מהאובייקט props את השדות בשמותיהם. דוגמה:
//   props = { user: {...}, siteName: '...' }
//   { user, siteName } => משתנה user ומשתנה siteName
function Header({ user, siteName }) {
  return (
    // <header> הוא תג HTML סמנטי (Semantic HTML) -
    // "סמנטי" = התג מתאר את המשמעות של התוכן ולא רק את העיצוב
    <header className="app-header">
      {/* siteName מגיע מהאב. אם משום מה לא הועבר - נציג טקסט חלופי */}
      <h1>{siteName ?? 'כותרת'}</h1>

      {/* user הוא אובייקט (אוסף של כמה שדות). ניגשים לשדות שלו בנקודה: user.fullName */}
      <p className="greeting">שלום, {user.fullName}</p>

      {/* role הוא שדה בתוך אובייקט user */}
      <p className="role">{user.role}</p>
    </header>
  )
}

export default Header
