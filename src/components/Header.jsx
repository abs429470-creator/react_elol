// ============================================================
// Header.jsx - קומפוננטת כותרת (קומפוננטת ילד)
// ============================================================
// קומפוננטה = פונקציה שמחזירה JSX (תיאור של מה שיוצג על המסך).
// הפונקציה מקבלת פרמטר אחד - props - שהוא אובייקט עם כל הנתונים
// שהקומפוננטה-האב העבירה לה.
// ============================================================

// הסוגריים המסולסלים סביב { user } ו-{ siteName } הם "destructuring":
// במקום לכתוב props.user ו-props.siteName, אנחנו "שולפים" החוצה
// מהאובייקט props את השדות בשמותיהם. דוגמה:
//   props = { user: {...}, siteName: '...' }
//   { user, siteName } => משתנה user ומשתנה siteName
function Header({ user, siteName }) {
  return (
    // <header> הוא תג HTML סמנטי (Semantic HTML) -
    // "סמנטי" = התג מתאר את המשמעות של התוכן ולא רק את העיצוב
    <header className="app-header">
      {/* siteName מגיע מהאב. אם משום מה לא הועבר - נציג טקסט חלופי */}
      <h1>{siteName ?? 'כותרת'}</h1>

      {/*
        --- למה יש כאן && ? ---

        עכשיו שהמשתמש מקליד את שמו בעצמו, ייתכן שעדיין לא הקליד כלום.
        במקרה כזה user.fullName הוא מחרוזת ריקה '' - ואסור להציג
        "שלום, " בלי שם. כלומר: *רוצים להציג את השורה רק בתנאי שיש שם*.

        ב-JSX לא כותבים if. במקום זה משתמשים בתבנית נפוצה מאוד:
            condition && <משהו />
        איך זה עובד? ב-JS הביטוי a && b מחזיר:
          - אם a "שקרי" (falsy) -> את a עצמו, בלי לבדוק את b בכלל.
          - אם a "אמיתי" (truthy) -> את b.
        ומכיוון שמחרוזת ריקה '' היא falsy, כשאין שם הביטוי מחזיר ''
        ו-React לא מצייר כלום. כשיש שם - הביטוי מחזיר את כל התג.

        חשוב: זוהי הסיבה שמעדיפים && ולא ביטוי שמחזיר 0 - כי React
        *כן* הייתה מציירת את הספרה 0 על המסך. מחרוזת ריקה לעומת זאת
        לא מייצרת כלום, ולכן היא בטוחה כאן.
      */}
      {user.fullName && <p className="greeting">שלום, {user.fullName}</p>}

      {/* אותו רעיון בדיוק עבור התפקיד - מוצג רק אחרי שהוקלד משהו */}
      {user.role && <p className="role">{user.role}</p>}
    </header>
  )
}

export default Header
