// ============================================================
// NewTaskForm.jsx - טופס להוספת משימה חדשה (קומפוננטת ילד)
// ============================================================
// הקומפוננטה הזו נראית מוכרת מ-NameForm - ומשום שהיא באמת בנויה
// על אותו דפוס בדיוק:
//   - היא מחזיקה מצב מקומי רק עבור *מה שכתוב בתיבה*.
//   - הנתון העסקי (רשימת המשימות) יושב באב, ולא כאן.
//   - הבן רק מדווח לאב מה הוקלד, דרך onAddTask.
//
// ההבדל המרכזי מ-NameForm: כאן הבן *מפעיל פעולה* (הוספה) ולא
// רק *מעדכן ערך*. לכן ההעברה לאב קורית ברגע השליחה - ולא בכל הקלדה.

// useState - כדי לזכור מה כתוב בתיבה בין הקלדה להקלדה.
import { useState } from 'react'

// קומפוננטת טופס היא ההזדמנות הטבעית להכיר את תג <form> האמיתי.
// הוא נותן לנו התנהגות דפדפן מובנית וחשובה: לחיצה על Enter בתיבה
// מפעילה את הטופס - כלומר, אפשר להוסיף משימה בלי לעזוב את המקלדת.
// זו הסיבה להעדיף <form> על "סתם div עם כפתור".
function NewTaskForm({ onAddTask }) {
  // המצב המקומי: הטקסט של המשימה החדשה. שוב - מחרוזת ריקה בהתחלה,
  // כלומר התיבה ריקה עד שהמשתמש מקליד.
  const [text, setText] = useState('')

  // handleChange רץ בכל הקלדה. הוא *לא* מדווח לאב - הוא רק שומר
  // את מה שהוקלד במצב המקומי, כדי שהתיבה המבוקרת לא "תקפא".
  const handleChange = (e) => {
    setText(e.target.value)
  }

  // ---------- השליחה ----------
  // הפונקציה הזו רצה כשהמשתמש לוחץ על "הוסף" או לוחץ Enter.
  const handleSubmit = (e) => {
    // !!! שורה קריטית !!!
    // ברירת המחדל של דפדפן לשליחת טופס היא *לטעון מחדש את העמוד*.
    // באפליקציית React עמוד שמתרענן = כל ה-state נמחק, וכל מה
    // שהמשתמש הקליד הולך לאיבוד. לכן תמיד חוסמים את ברירת המחדל.
    // זו התקלה מספר 1 של מתחילים עם טפסים ב-React.
    e.preventDefault()

    // trim() מסיר רווחים מההתחלה ומהסוף. המחרוזת "   " אמורה
    // להיחשב ריקה. בלי הבדיקה הזו אפשר להוסיף "משימה" שאין בה כלום.
    const trimmed = text.trim()

    // הגנה: אם אחרי הניקוי לא נשאר טקסט - לא עושים כלום ויוצאים.
    // return "מוקדם" חוסך לנו קינון של כל שאר הקוד בתוך if.
    if (!trimmed) return

    // מדווחים לאב: "המשתמש רוצה להוסיף משימה בשם הזה".
    // האב הוא שיחליט איך להוסיף אותה בפועל (איזה id, סדר וכו').
    onAddTask(trimmed)

    // מרוקנים את התיבה - הכנה להקלדה הבאה.
    // שימו לב: לא נוגעים ב-רשימה עצמה! רק במצב המקומי של הטופס.
    setText('')
  }

  return (
    // onSubmit={handleSubmit} - נקרא בדיוק פעם אחת, בעצם השליחה.
    // זו הדרך המומלצת: היא מכסה גם את הכפתור וגם את מקש Enter.
    <form className="new-task-form" onSubmit={handleSubmit}>
      <label htmlFor="new-task">משימה חדשה</label>
      <input
        id="new-task"
        type="text"
        value={text}             // מבוקר - מציג תמיד את מצב הטופס
        onChange={handleChange}  // כל הקלדה -> עדכון המצב המקומי
        placeholder="תיאור"
      />
      {/*
        type="submit" (ולא type="button") - זה מה שמפעיל את onSubmit
        של הטופס. כפתור בלי type, או עם type="submit", ישלח את הטופס;
        type="button" לעומת זאת לא יעשה דבר בעצמו.
      */}
      <button type="submit">הוסף</button>
    </form>
  )
}

export default NewTaskForm
