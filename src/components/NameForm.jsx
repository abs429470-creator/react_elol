// ============================================================
// NameForm.jsx - טופס להזנת שם ותפקיד (קומפוננטת ילד)
// ============================================================
// זו קומפוננטה חדשה. תפקידה היחיד: לאפשר למשתמש להקליד את שמו
// ואת תפקידו, ולדווח לאב על כל הקלדה.
//
// שימו לב לחלוקת האחריות (זו נקודה מרכזית ב-React):
//   - הנתונים האמיתיים (השם והתפקיד) יושבים ב-App, קומפוננטת האב.
//   - הקומפוננטה הזו לא "מחזיקה" אותם. היא רק מציירת שני שדות קלט
//     ומודיעה לאב מה המשתמש הקליד, דרך onNameChange / onRoleChange.
// זה בדיוק אותו דפוס של onToggleTask ב-TaskList - "האב מחזיק,
// הבן מדווח". לכן האב יכול להשתמש באותו שם גם בכותרת וגם בסיכום.

// מייבאים useState, כי לקומפוננטה הזו יש מצב מקומי משלה (ראו בפנים).
import { useState } from 'react'

// destructuring של props: שולפים החוצה את שם הכותרת ואת שתי
// פונקציות-המאורע שהאב מעביר. הכיתוב on... מסמן מיד שאלה פונקציות
// שהבן קורא להן, ולא נתונים שהבן קורא מהם.
function NameForm({ siteName, onNameChange, onRoleChange }) {
  // ---------- המצב המקומי של הטופס ----------
  // מדוע יש כאן useState בכלל, אם הנתונים יושבים באב?
  // משום שיש שני "סוגי" מידע שונים:
  //   1. הנתון העסקי - "מי המשתמש". הוא שייך לאב ולכן שם הוא נשמר.
  //   2. מצב התיבה עצמה - "מה כתוב כרגע בתיבה". זה עניין פנימי של הטופס.
  // הפרדה כזו נקראת "מקור אמת יחיד לכל נתון": לאותו ערך לא יהיו
  // שני "בעלים" שיכולים להיפרד זה מזה.
  //
  // ה-מצב ההתחלתי הוא מחרוזת ריקה '', כלומר - התיבה ריקה עד שהמשתמש
  // מקליד. לכן לפני הקלדה אין כלום להציג, ואכן לא מוצג שם ולא תפקיד.
  const [name, setName] = useState('')
  const [role, setRole] = useState('')

  // ---------- מטפל השינוי של תיבת השם ----------
  // הפונקציה מקבלת את "מאורע" (event) - אובייקט שמתאר מה קרה במסך.
  // e.target הוא האלמנט שבו קרה המאורע, ו-e.target.value הוא
  // הטקסט שנמצא כרגע בתיבת הקלט.
  //
  // כאן יש "תיבת קלט מבוקרת" (controlled input) - בדיוק כמו ה-checkbox
  // ב-TaskList: התיבה לא זוכרת את הטקסט בעצמה, אלא מציגה תמיד את מה
  // שיש ב-state (value={name}). לכן חייבים לעדכן את ה-state בכל הקלדה,
  // ואם לא נעשה זאת - התיבה "תקפא" ולא תקבל אותיות.
  const handleNameChange = (e) => {
    const newName = e.target.value // מה שהמשתמש הקליד כרגע
    setName(newName)              // עדכון המצב המקומי -> מסך מתרענן
    onNameChange(newName)         // דיווח לאב -> יעדכן את המשתמש שלו
  }

  // אותו דבר בדיוק עבור תיבת התפקיד.
  const handleRoleChange = (e) => {
    const newRole = e.target.value
    setRole(newRole)
    onRoleChange(newRole)
  }

  // ---------- התצוגה (JSX) ----------
  return (
    <section className="name-form">
      {/* הכותרת מגיעה מהאב - כדי שלא נכתוב אותה פעמיים בקוד */}
      <h2>{siteName ?? 'כותרת'}</h2>

      {/*
        <label> מקשר טקסט לתיבת קלט. htmlFor מקביל ל-for ב-HTML
        (ב-JSX כותבים htmlFor, מפני ש-for היא מילה שמורה).
        הקישור חשוב גם לנגישות וגם לנוחות: לחיצה על הכיתוב
        מעבירה את הסמן ישר לתיבה.
        שם ה-id חייב להיות ייחודי בכל העמוד - לכן 'user-name' / 'user-role'.
      */}
      <div className="form-row">
        <label htmlFor="user-name">שם</label>
        <input
          id="user-name"
          type="text"
          value={name}                    // מבוקר: התיבה מציגה את ה-state
          onChange={handleNameChange}     // כל הקלדה -> עדכון + דיווח לאב
          placeholder="שם מלא"
        />
      </div>

      {/*
        שימו לב: value={role} ולא value={user.role}.
        ה-state שלנו נקרא role, וכך גם ה-prop של Header - שני שמות
        שונים לדברים שונים, וזה תקין. להיפך - היה מבלבל לתת להם אותו שם.
      */}
      <div className="form-row">
        <label htmlFor="user-role">תפקיד</label>
        <input
          id="user-role"
          type="text"
          value={role}
          onChange={handleRoleChange}
          placeholder="תפקיד"
        />
      </div>
    </section>
  )
}

export default NameForm
