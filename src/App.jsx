// ============================================================
// App.jsx - קומפוננטת האב (Parent Component)
// ============================================================
// זהו "הרכיב הראשי" של האפליקציה. הוא:
//   1. מחזיק את הנתונים (משימות + פרטי המשתמש)
//   2. מייבא את שלוש קומפוננטות-הבן
//   3. מרנדר אותן ומעביר להן את הנתונים כ-props
//
// חשוב: App.jsx הוא היחיד שמכיר את הנתונים. הבנים מקבלים אותם
// "מן המוכן" ולא נוגעים בהם. זרימת המידע היא תמיד מהאב לבן - בכיוון אחד.
// ============================================================

// ייבוא הקומפוננטות. הנתיב ./components/... הוא יחסי לקובץ הנוכחי (src/).
// (בסביבות מודרניות אין חובה לכתוב את הסיומת .jsx - Vite משלים אותה לבד.)
// ייבוא useState מתוך React - הפונקציה שמאפשרת לקומפוננטה
// "לזכור" מידע שמשתנה בזמן הריצה (ראו הסבר בפנים).
import { useState } from 'react'
import Header from './components/Header.jsx'
import TaskList from './components/TaskList.jsx'
import Summary from './components/Summary.jsx'
import NameForm from './components/NameForm.jsx'
import NewTaskForm from './components/NewTaskForm.jsx'
import './App.css'

function App() {
  // ---------- הנתונים (Data) ----------
  // עד עכשיו tasks היה פשוט משתנה "רגיל" שנקרא פעם אחת ולא השתנה.
  // מהרגע שאנחנו רוצים שהמשתמש יוכל לשנות את המשימות בזמן הריצה,
  // אנחנו חייבים להפוך אותו ל"מצב" (state) של הקומפוננטה.
  //
  // useState מחזיר מערך עם שני איברים:
  //   1. tasks        - הערך הנוכחי של המצב (גישה לקריאה בלבד!)
  //   2. setTasks     - פונקציה לשני את הערך. כשהיא נקראת, React
  //                     מדפיסה מחדש את הקומפוננטה עם הערך החדש.
  //
  // חשוב: לעולם לא משנים את tasks ישירות (tasks.push = אסור!).
  // תמיד עוברים דרך setTasks, כדי ש-React תדע שהמסך חייב להתעדכן.
  //
  // שיפרנו גם את המבנה של כל משימה: במקום status כמחרוזת (הושלמה/בתהליך...)
  // התחלנו לשדה בוליאני completed (true = הושלמה, false = לא).
  // זה טבעי יותר לעבודה עם checkbox, וברור יותר לקריאה: completed: true.
  const [tasks, setTasks] = useState([
    { id: 1, name: 'פריט 1', completed: true },
    { id: 2, name: 'פריט 2', completed: true },
    { id: 3, name: 'פריט 3', completed: false },
    { id: 4, name: 'פריט 4', completed: false },
    { id: 5, name: 'פריט 5', completed: false },
    { id: 6, name: 'פריט 6', completed: false },
  ])

  // ---------- פונקציית עזר: החלפת מצב של משימה אחת ----------
  // המטלה: "סימון משימה כהושלמה/לא הושלמה". הפונקציה הזו מקבלת
  // מזהה (id) של משימה, ומחליפה את שדה completed שלה.
  //
  // מדוע הפונקציה חיה כאן (באב) ולא בתוך TaskList?
  // משום שהנתונים עצמם (tasks) נמצאים כאן. לפי עקרון "מקור אמת יחיד"
  // (Single Source of Truth), מי שמחזיק בנתון הוא גם זה שצריך לשנות אותו.
  // הבן (TaskList) רק "מדווח" לאב שהמשתמש לחץ - והאב משנה את הנתון.
  //
  // איך זה עובד? map יוצר מערך חדש. לכל משימה:
  //   - אם ה-id שלה שווה ל-id שקיבלנו -> החזר עותק שלה עם completed הפוך.
  //   - אחרת -> החזר אותה בדיוק כמו שהיא.
  // את המערך החדש הזה אנחנו שולחים ל-setTasks. React משווה ומעדכנת.
  //
  // (props, ...task) = spread: "מורח" את כל השדות הקיימים של task
  // לתוך האובייקט החדש, ואז אנחנו דורסים רק את completed.
  const toggleTask = (id) => {
    setTasks((prevTasks) =>
      prevTasks.map((task) =>
        task.id === id ? { ...task, completed: !task.completed } : task
      )
    )
  }

  // ---------- הוספת משימה חדשה ----------
  // הפונקציה מקבלת מהטופס את הטקסט שהוקלד (כבר נקי מרווחים מיותרים).
  // את השם text בחרתי ולא name, כדי לא להתבלבל עם שדה השם של המשתמש.
  //
  // שלוש נקודות שחשוב להבין כאן:
  //
  // 1. למה כל המשימות מקבלות אותו completed: false?
  //    משימה חדשה טרם בוצעה - זה מובן מאליו, אבל שווה לשים לב
  //    ש-*כל* משימה חייבת להכיל את כל השדות שהקוד מצפה להם.
  //    אילו שכחנו את completed, ה-checkbox היה מקבל undefined
  //    ומופיע כלא-מסומן "במקרה" - ואז סימון היה מתנהג מוזר.
  //    עדיף תמיד לכתוב את השדה במפורש.
  //
  // 2. מניין מגיע ה-id? מ-Date.now() - הפונקציה שמחזירה את מספר
  //    המילישניות מאז 1.1.1970. בכל לחיצה זה מספר שונה, ולכן הוא
  //    *בפועל* ייחודי. זו שיטה מקובלת בתרגול.
  //    אזהרה למציאות: זו אינה שיטה מושלמת - שנייה שבה נוצרות שתי
  //    משימות באותה מילישנייה תקבל אותו id. בפרויקט אמיתי ששומר
  //    נתונים בשרת, ה-id יגיע מהשרת. לתרגיל כאן זה מספיק בהחלט.
  //
  // 3. למה [newTask, ...prevTasks] ולא prevTasks.push(newTask)?
  //    זו הנקודה החשובה ביותר בכל השלב.
  //    *אסור* לשנות את המערך הקיים! React מזהה שינוי בכך שהיא
  //    משווה את ההפניה (reference) - אם היינו משנים את אותו מערך,
  //    ההפניה הייתה נשארת זהה ו-React הייתה *מדלגת* על העדכון,
  //    והמשימה החדשה פשוט לא הייתה מופיעה.
  //    לכן יוצרים מערך *חדש*. ה-... (spread) "פורש" את המשימות
  //    הקיימות, ומשימים את החדשה *לפניה* - כך היא מופיעה בראש
  //    הרשימה, מה שהמשתמש מצפה לו אחרי שלחץ "הוסף".
  //    העיקרון: לא משנים נתון קיים - יוצרים עותק חדש ומעודכן.
  const addTask = (text) => {
    const newTask = {
      id: Date.now(),
      name: text,
      completed: false,
    }

    setTasks((prevTasks) => [newTask, ...prevTasks])
  }

  // ---------- פרטי המשתמש (השלב הנוכחי) ----------
  // עד עכשיו user היה אובייקט "קבוע" עם שם ותפקיד כתובים בקוד.
  // עכשיו המשתמש מקליד אותם בעצמו - ולכן הם חייבים להיות state.
  //
  // שימו לב: שמרנו על *אותו שם* למשתנה (user) ולשדות שבתוכו
  // (fullName, role). היתרון: כל שאר הקוד שמשתמש ב-user.fullName
  // ממשיך לעבוד בדיוק כמו קודם, בלי שינוי.
  //
  // הערכים ההתחלתיים הם מחרוזות ריקות. מחרוזת ריקה היא "אין טקסט",
  // ולכן היא בדיוק מה שאנחנו רוצים: לפני שהמשתמש הקליד - לא מוצג כלום.
  //
  // הנתונים יושבים כאן, באב, מפני ששני בנים שונים צריכים אותם
  // (Header ו-Summary). אם הם היו יושבים באחד הבנים, השני לא היה
  // מגיע אליהם. ההכלל המקובל: "מרימים את המצב למעלה" (lifting state up)
  // אל האב המשותף הקרוב ביותר.
  const [user, setUser] = useState({
    fullName: '',
    role: '',
  })

  // ---------- עדכון שם המשתמש ----------
  // פונקציה שמקבלת את השם החדש ומעדכנת את המצב.
  //
  // מדוע (prevUser) => ({...}) ולא setUser ישירות? כי אנחנו מעדכנים
  // *חלק* מאובייקט וצריכים לשמר את שאר השדות. ה-spread (...prevUser)
  // "מורח" את השדות הקיימים לתוך אובייקט חדש, ורק fullName נדרס.
  // כך role לא נמחק כשמעדכנים את השם - וזה בדיוק מה שרצינו.
  //
  // מדוע סוגריים עגולים סביב { ...prevUser, ... }? כי גוף של פונקציית
  // חץ שמתחיל בסוגריים מסולסלים נקרא עלול להיראות כמו "בלוק קוד"
  // ולא כמו אובייקט. הסוגריים העגולים מבהירים ל-JS: זה ערך מוחזר.
  //
  // מדוע setUser((prevUser) => ...) ולא setUser({...user, ...})?
  // שתי הצורות עובדות, אך זו שמקבלת את המצב הקודם מהפרמטר בטוחה יותר:
  // היא תמיד מבוססת על הערך העדכני ביותר, גם אם היו כמה עדכונים
  // ברצף מהיר. זו הדרך המומלצת לעדכון שמבוסס על הערך הקודם.
  const handleNameChange = (newName) => {
    setUser((prevUser) => ({ ...prevUser, fullName: newName }))
  }

  // ---------- עדכון התפקיד ----------
  // בדיוק אותו דפוס, רק שהפעם דורסים את role ומשאירים את fullName.
  const handleRoleChange = (newRole) => {
    setUser((prevUser) => ({ ...prevUser, role: newRole }))
  }

  // קבוע לכותרת האתר.
  const siteName = 'ניהול משימות'

  // ---------- התצוגה (JSX) ----------
  return (
    // <div className="app"> הוא "עוטף" אחד לכל האפליקציה, כדי שנוכל לעצב אותה.
    // שימו לב: ב-JSX כותבים className ולא class (כי class היא מילה שמורה ב-JS),
    // והערך הוא מחרוזת - שם של מחלקת CSS.
    <div className="app">
      {/*
        --- העברת נתונים לקומפוננטת הבן (props) ---
        הכתיב <Header user={user} siteName={siteName} /> יוצר "תג" של הקומפוננטה
        שלנו, בדיוק כמו <div>. כל מה שבתוך התג נהפך לשדות באובייקט props
        שמתקבל בתוך Header. בתוך { } כותבים ביטוי JS - כאן שם של משתנה.
        לכן user={user} מעביר הלאה את המשתנה user.
      */}
      <Header user={user} siteName={siteName} />

      {/*
        --- טופס הזנת השם והתפקיד ---
        כאן מעבירים שלושה דברים:
          siteName        - נתון (מחרוזת), כמו ב-Header.
          onNameChange    - פונקציה שהאב נותן לבן. הטופס יקרא לה
                            בכל הקלדה וימסור את מה שהוקלד.
          onRoleChange    - אותו דבר עבור התפקיד.

        שימו לב לשם: הנתון נקרא user, והפונקציות מתחילות ב-on.
        ההפרדה הזו היא לב העניין: "נתונים מלמעלה למטה, אירועים
        מלמטה למעלה". הטופס לא יכול לשנות את user בעצמו - הוא
        רק מבקש מהאב לעשות זאת.
      */}
      <NameForm
        siteName={siteName}
        onNameChange={handleNameChange}
        onRoleChange={handleRoleChange}
      />

      {/*
        כאן מעבירים ל-TaskList שני דברים:
          tasks          - כל המשימות (כמו קודם).
          onToggleTask   - "החכה" (callback) שאב נותן לילד.
                           TaskList לא יודעת איך לשנות את הנתונים -
                           היא רק תקרא לפונקציה הזו כשהמשתמש יסמן משימה,
                           והיא תדווח לאב איזה id צריך להפוך.
        המוסכמה: שמות של פונקציות-מאורע מתחילים ב-on (onClick, onChange,
        onToggleTask...). כך ברור שזה "קול" שהבן משמיע, לא נתון.
      */}
      {/*
        --- טופס הוספת משימה ---
        מעבירים רק דבר אחד: את הפונקציה addTask.
        אין כאן prop של נתונים, כי לטופס אין צורך בהם - הוא לא מצייר
        את הרשימה, הוא רק מוסיף אליה. קומפוננטה שמקבלת רק את מה שהיא
        צריכה היא קומפוננטה קלה יותר לבדיקה ולתחזוקה.

        שימו לב לסדר: הטופס מוצג *לפני* הרשימה, כדי שהמשתמש יראה
        את מה שהוסיף מיד מתחת למקום שבו לחץ.
      */}
      <NewTaskForm onAddTask={addTask} />

      <TaskList tasks={tasks} onToggleTask={toggleTask} />

      {/*
        כאן מעבירים שני דברים: את כל המערך ואת שם המשתמש.
        הקומפוננטה עצמה תחשב כמה משימות יש וכמה הושלמו -
        היא לא מקבלת מספרים מוכנים, אלא גוזרת אותם מהנתונים.
      */}
      <Summary tasks={tasks} userName={user.fullName} />
    </div>
  )
}

// ייצוא ברירת מחדל (default export) - מאפשר לייבוא את הפונקציה
// בשם שאנחנו בוחרים בקובץ אחר (ראו main.jsx: import App from './App.jsx').
export default App
